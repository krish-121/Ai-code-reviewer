@pytest.mark.parametrize(
    "line",
    [
        'password = os.environ["PASSWORD"]',
        'api_key = "changeme-please"',
        'token = "${TOKEN_FROM_ENV}"',
        'secret = "aaaaaaaaaaaa"',
        "max_tokens = 4096",
        'password = "short"',
        """cur.execute(f"SELECT * FROM u WHERE name = '{name}' AND password = '{password}'")""",
        "token = '%(token)s-template'",
    ],
)
def test_scanner_ignores_placeholders(line: str) -> None:
    assert scan_line(line, 1) == []


def test_redact_text_private_key_block() -> None:
    text = "a\n-----BEGIN PRIVATE KEY-----\nMIIBVQIBADANBg\n-----END PRIVATE KEY-----\nb"
    red, n = redact_text(text)
    assert "MIIBVQ" not in red and n >= 1
    assert red.startswith("a\n[REDACTED:private-key]")


def test_scan_text_skips_key_body() -> None:
    text = "-----BEGIN PRIVATE KEY-----\nAKIAABCDEFGHIJKLMNOP\n-----END PRIVATE KEY-----\n"
    matches = scan_text(text)
    assert [m.rule.id for m in matches] == ["private-key"]


def test_entropy() -> None:
    assert shannon_entropy("") == 0.0
    assert shannon_entropy("aaaa") == 0.0
    assert shannon_entropy("abcd") == 2.0
