"""File filtering, secret detection/redaction and prompt-injection scanning."""

from __future__ import annotations

import pytest

from sentinel.analysis.diff.filtering import filter_changeset, sensitive_file_reason
from sentinel.analysis.diff.parser import parse_unified_diff, whole_file_change
from sentinel.analysis.diff.secrets import redact_text, scan_line, scan_text, shannon_entropy
from sentinel.core.domain.models import (
    Category,
    ChangeSet,
    FindingSource,
    Language,
    Severity,
)

AWS = "AKIA" + "ABCDEFGHIJKLMNOP"
GH = "ghp_" + "a1B2c3D4e5F6g7H8i9J0k1L2m3N4o5P6q7R8"


def _cs(*files: tuple[str, str]) -> ChangeSet:
    return ChangeSet(files=[whole_file_change(p, c) for p, c in files])


def test_sensitive_files_are_dropped_and_reported() -> None:
    cs = _cs((".env", "DB_PASSWORD=hunter2hunter2\n"), ("keys/id_rsa", "x\n"), ("app.py", "x=1\n"))
    out = filter_changeset(cs)
    assert [f.path for f in out.changeset.files] == ["app.py"]
    reasons = {s.path: s.reason for s in out.changeset.skipped}
    assert "never sent to AI" in reasons[".env"]
    assert {f.file for f in out.findings} == {".env", "keys/id_rsa"}
    assert all(f.severity is Severity.HIGH for f in out.findings)
    assert all(f.source is FindingSource.STATIC_ANALYZER for f in out.findings)


def test_env_templates_are_not_sensitive() -> None:
    assert sensitive_file_reason(".env.example") is None
    assert sensitive_file_reason("config/.env.production") is not None


@pytest.mark.parametrize(
    ("path", "reason"),
    [
        ("static/logo.png", "binary file"),
        ("package-lock.json", "lock file"),
        ("proto/user_pb2.py", "generated file"),
        ("node_modules/x/index.js", "generated file"),
        ("dist/app.min.js", "generated file"),
        ("generated/models.py", "ignored by .sentinel.yml"),
    ],
)
def test_skip_reasons(path: str, reason: str) -> None:
    out = filter_changeset(_cs((path, "content\n")), ignore=["generated/"])
    assert out.changeset.files == []
    assert out.changeset.skipped[0].reason == reason


def test_minified_detection() -> None:
    long_line = "var a=1;" * 80
    out = filter_changeset(_cs(("bundle.js", long_line + "\n")))
    assert out.changeset.skipped[0].reason == "minified file"


def test_generated_marker() -> None:
    out = filter_changeset(_cs(("api/client.ts", "// @generated by openapi\nexport {}\n")))
    assert out.changeset.skipped[0].reason == "generated file"


def test_ignore_globs() -> None:
    cs = _cs(("db/migrations/0001.py", "x\n"), ("a/b.sql", "x\n"), ("keep.py", "x\n"))
    out = filter_changeset(cs, ignore=["migrations/", "*.sql", "# comment", ""])
    assert [f.path for f in out.changeset.files] == ["keep.py"]


def test_language_filter() -> None:
    cs = _cs(("a.py", "x=1\n"), ("b.ts", "let x=1\n"))
    out = filter_changeset(cs, languages=[Language.PYTHON])
    assert [f.path for f in out.changeset.files] == ["a.py"]
    assert "language not enabled" in out.changeset.skipped[0].reason


def test_secret_in_added_line_is_reported_and_redacted() -> None:
    diff = f"""\
diff --git a/cfg.py b/cfg.py
--- a/cfg.py
+++ b/cfg.py
@@ -1,2 +1,3 @@
 import os
+AWS_KEY = "{AWS}"
 KEY = os.environ["KEY"]
"""
    out = filter_changeset(parse_unified_diff(diff))
    assert out.redactions == 1
    (finding,) = out.findings
    assert finding.category is Category.SECURITY
    assert finding.line_start == 2
    assert AWS not in finding.model_dump_json()
    added = out.changeset.files[0].hunks[0].lines[1].content
    assert AWS not in added and "[REDACTED:aws-access-key]" in added


def test_secret_in_context_line_is_redacted_but_not_reported() -> None:
    diff = f"""\
diff --git a/cfg.py b/cfg.py
--- a/cfg.py
+++ b/cfg.py
@@ -1,2 +1,3 @@
 TOKEN = "{GH}"
+x = 1
 y = 2
"""
    out = filter_changeset(parse_unified_diff(diff))
    assert out.findings == []
    assert GH not in out.changeset.files[0].hunks[0].lines[0].content


