import assert from "node:assert/strict";
import { afterEach, test } from "node:test";
import { JSDOM } from "jsdom";
import { createElement } from "react";
import { cleanup, render, waitFor } from "@testing-library/react";

import { api } from "../src/lib/api";
import { invalidate } from "../src/lib/hooks";
import type { FixAttempt, ReviewDetail } from "../src/lib/types";
import { FixPanel } from "../src/findings/FixPanel";
import { ReviewHeader } from "../src/pages/ReviewPage";
import { OverviewTab } from "../src/review/OverviewTab";

const dom = new JSDOM("<!doctype html><html><body></body></html>", { url: "http://localhost" });
Object.assign(globalThis, {
  window: dom.window,
  document: dom.window.document,
  HTMLElement: dom.window.HTMLElement,
});
const originalFix = api.fix;
afterEach(() => {
  cleanup();
  api.fix = originalFix;
  invalidate("");
});

function review(update: Partial<ReviewDetail> = {}): ReviewDetail {
  return {
    id: "browser",
    title: "Staged change",
    status: "completed",
    risk: "none",
    source: "staged",
    repository: "example",
    repository_kind: "local",
    pull_request: null,
    counts: {},
    headline: null,
    provider: null,
    model: null,
    created_at: null,
    finished_at: null,
    duration_ms: 10,
    summary: null,
    stages: [],
    errors: [],
    base_ref: null,
    head_ref: null,
    usage: { input_tokens: 0, output_tokens: 0 },
    published_at: null,
    mode: "staged",
    analysis_runs: [],
    can_apply_fixes: true,
    ...update,
  };
}

test("a queued AI review does not pretend to be static-only", () => {
  const view = render(createElement(ReviewHeader, { review: review({ status: "queued" }) }));
  assert.match(view.container.textContent ?? "", /Awaiting review result/);
  assert.doesNotMatch(view.container.textContent ?? "", /Static analysis only/);
});

test("a failed AI stage is unavailable rather than an actual fallback model result", () => {
  const view = render(
    createElement(ReviewHeader, {
      review: review({
        status: "partial",
        provider: "fallback",
        model: "gemini -> deepseek",
        stages: [
          {
            name: "ai_review",
            status: "failed",
            detail: "HTTP 503",
            duration_ms: 1,
            started_at: null,
            metrics: {},
          },
        ],
      }),
    }),
  );
  assert.match(view.container.textContent ?? "", /AI review unavailable/);
  assert.doesNotMatch(view.container.textContent ?? "", /fallback \/ gemini/);
});

test("a completed fallback review identifies the actual model", () => {
  const view = render(
    createElement(ReviewHeader, {
      review: review({
        provider: "opencode",
        model: "deepseek-v4.1-flash-free",
      }),
    }),
  );
  assert.match(view.container.textContent ?? "", /opencode \/ deepseek-v4.1-flash-free/);
});

test("older partial summaries with no uncertainty text still warn about incomplete checks", () => {
  const view = render(
    createElement(OverviewTab, {
      review: review({ status: "partial", errors: ["ai_review: HTTP 503"] }),
      findings: [],
    }),
  );
  assert.match(view.container.textContent ?? "", /This review is incomplete/);
  assert.doesNotMatch(view.container.textContent ?? "", /Every surfaced finding was confirmed/);
});

for (const [provider, model] of [
  ["gemini", "gemini-3.8-flash"],
  ["opencode", "deepseek-v4.1-flash-free"],
]) {
  test(`a validated fix displays its actual ${provider} model`, async () => {
    api.fix = async (id): Promise<FixAttempt> => ({
      id,
      finding_id: "F",
      status: "validated",
      summary: "A validated fix",
      patch: null,
      checks: [],
      isolation: "docker",
      provider: provider!,
      model: model!,
      attempts: 1,
      error: null,
      created_at: null,
      finished_at: null,
      can_apply: true,
    });
    const view = render(
      createElement(FixPanel, { fixId: provider!, canApply: true, onApplied() {} }),
    );
    await waitFor(() => assert.match(view.container.textContent ?? "", /Generated by:/));
    assert.ok(view.container.textContent?.includes(`${provider} / ${model}`));
    assert.ok(view.getByRole("button", { name: "Apply to working tree" }));
  });
}
