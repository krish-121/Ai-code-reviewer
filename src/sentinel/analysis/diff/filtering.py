SAFE_ENV_TEMPLATES = (".env.example", ".env.sample", ".env.template", ".env.dist")

MAX_FILE_CHANGED_LINES = 4000
MINIFIED_AVG_LINE = 400


@dataclass
class FilterOutcome:
    """The filtered change set, findings about secrets/sensitive files, and the redaction count."""

    changeset: ChangeSet
    findings: list[Finding] = field(default_factory=list)
    redactions: int = 0


def _matches_ignore(path: str, patterns: list[str]) -> bool:
    for raw in patterns:
        pat = raw.strip()
        if not pat or pat.startswith("#"):
            continue
        if pat.endswith("/"):
            if path.startswith(pat) or f"/{pat}" in f"/{path}":
                return True
            continue
        if fnmatch.fnmatch(path, pat) or fnmatch.fnmatch(posixpath.basename(path), pat):
            return True
        if fnmatch.fnmatch(path, f"*/{pat}"):
            return True
    return False


def sensitive_file_reason(path: str) -> tuple[Severity, str] | None:
    """``(severity, description)`` when the file must never be read or sent to a model."""
    base = posixpath.basename(path).lower()
    if base in SAFE_ENV_TEMPLATES:
        return None
    for glob, severity, reason in SENSITIVE_FILES:
        if fnmatch.fnmatch(base, glob):
            return severity, reason
    return None


def source_exclusion_reason(
    path: str, ignore: list[str] | None = None, languages: list[Language] | None = None
) -> str | None:
    """Shared path policy for diff, graph/context, snapshots and fix requests."""
    if sensitive_file_reason(path):
        return "sensitive file"
    if _matches_ignore(path, ignore or []):
        return "ignored by .sentinel.yml"
    low = path.lower()
    if any(low.startswith(d) or f"/{d}" in low for d in GENERATED_DIRS):
        return "generated directory"
    if low.endswith((*GENERATED_SUFFIXES, ".d.ts")):
        return "generated file"
    if posixpath.basename(low) in LOCK_FILES or posixpath.splitext(low)[1] in BINARY_EXTENSIONS:
        return "binary or lock file"
    if languages and detect_language(path) not in languages:
        return "language not enabled"
    return None


def _is_generated(change: FileChange) -> bool:
    """Build output, vendored code, or a file whose first lines say it is generated."""
    low = change.path.lower()
    if any(low.startswith(d) or f"/{d}" in low for d in GENERATED_DIRS):
        return True
    if low.endswith(GENERATED_SUFFIXES):
        return True
    head = [ln.content for h in change.hunks[:1] for ln in h.lines[:5]]
    return any(marker in line for line in head for marker in GENERATED_MARKERS)


def _is_minified(change: FileChange) -> bool:
    """JS/TS/CSS whose added lines are very long on average."""
    if change.language not in (Language.JAVASCRIPT, Language.TYPESCRIPT) and not (
        change.path.endswith(".css")
    ):
        return False
    lines = [ln.content for h in change.hunks for ln in h.lines if ln.kind is LineKind.ADDED]
    if not lines:
        return False
    avg = sum(len(x) for x in lines) / len(lines)
    return avg > MINIFIED_AVG_LINE


def _skip_reason(change: FileChange, ignore: list[str]) -> str | None:
    """Why a (non-sensitive) file is not worth reviewing, or None to review it."""
    base = posixpath.basename(change.path).lower()
    ext = posixpath.splitext(base)[1]
    if change.is_binary or ext in BINARY_EXTENSIONS:
        return "binary file"
    if base in LOCK_FILES:
        return "lock file"
    if _matches_ignore(change.path, ignore):
        return "ignored by .sentinel.yml"
    if _is_generated(change):
        return "generated file"
    if _is_minified(change):
        return "minified file"
    if change.additions + change.deletions > MAX_FILE_CHANGED_LINES:
        return f"too large ({change.additions + change.deletions} changed lines)"
    if any("\x00" in ln.content for h in change.hunks for ln in h.lines):
        return "binary content"
    return None


def _sensitive_change_reason(change: FileChange) -> tuple[Severity, str] | None:
    """A public destination cannot authorize a formerly sensitive source file."""
    return sensitive_file_reason(change.path) or sensitive_file_reason(change.old_path or "")


def _previous_path_reason(change: FileChange, ignore: list[str]) -> str | None:
    """Keep ignored/generated old content out of renamed-file context as well."""
    if not change.old_path or change.old_path == change.path:
        return None
    reason = source_exclusion_reason(change.old_path, ignore)
    return f"previous path: {reason}" if reason else None


def filter_changeset(
    changeset: ChangeSet,
    *,
    ignore: list[str] | None = None,
    languages: list[Language] | None = None,
) -> FilterOutcome:
    """Decide which changed files are reviewed, and redact secrets in the ones that are.

    Called by the orchestrator's filter stage, before anything reaches an AI provider.

    Args:
        changeset: The parsed diff. Diff lines of kept files are redacted in place.
        ignore: Glob patterns from ``.sentinel.yml`` (``ignore:``).
        languages: Languages enabled in ``.sentinel.yml``; None means all.
    """
    enabled = set(languages) if languages else None
    kept: list[FileChange] = []
    skipped: list[SkippedFile] = list(changeset.skipped)
    findings: list[Finding] = []
    redactions = 0
    for change in changeset.files:
        sensitive = _sensitive_change_reason(change)
        if sensitive is not None:
            severity, reason = sensitive
            note = f"sensitive file ({reason}) — never sent to AI"
            skipped.append(SkippedFile(path=change.path, reason=note))
            if change.change_type is not ChangeType.DELETED:
                findings.append(_sensitive_file_finding(change, severity, reason))
            continue
        skip = _skip_reason(change, ignore or []) or _previous_path_reason(change, ignore or [])
        if skip is not None:
            skipped.append(SkippedFile(path=change.path, reason=skip))
            continue
        findings += _secret_findings(change)
        redactions += _redact_in_place(change)
        if enabled is not None and change.language not in enabled:
            note = f"language not enabled ({change.language})"
            skipped.append(SkippedFile(path=change.path, reason=note))
            continue
        kept.append(change)
    filtered = changeset.model_copy(update={"files": kept, "skipped": skipped})
    return FilterOutcome(changeset=filtered, findings=findings, redactions=redactions)


def _secret_findings(change: FileChange) -> list[Finding]:
    """A finding for every secret on an added line."""
    return [
        _secret_finding(change.path, m.rule.id, m.rule.title, m.rule.confidence, m.line, m.masked)
        for hunk in change.hunks
        for line in hunk.lines
        if line.kind is LineKind.ADDED and line.new_lineno is not None
        for m in scan_line(line.content, line.new_lineno)
    ]


def _redact_in_place(change: FileChange) -> int:
    """Redact secrets on every diff line and return how many were replaced.

    Context and removed lines are redacted too, because the whole hunk is shown to the
    model.
    """
    count = 0
    original = {id(line): line.content for h in change.hunks for line in h.lines}
    # Redact old and new streams independently: an added END marker must not terminate
    # a removed private-key block (or vice versa). Preserve line numbering in both.
    for excluded in (LineKind.ADDED, LineKind.REMOVED):
        lines = [line for h in change.hunks for line in h.lines if line.kind is not excluded]
        if not lines:
            continue
        redacted, found = redact_text("\n".join(original[id(line)] for line in lines))
        count += found
        for line, content in zip(lines, redacted.split("\n"), strict=True):
            if content != original[id(line)]:
                line.content = content
    return count


def _article(word: str) -> str:
    """'a' or 'an' for ``word``."""
    return "an" if word[:1].lower() in "aeiou" else "a"


def _sensitive_file_finding(change: FileChange, severity: Severity, reason: str) -> Finding:
    return Finding(
        category=Category.SECURITY,
        severity=severity,
        confidence=0.9,
        title=f"Sensitive file committed: {posixpath.basename(change.path)}",
        explanation=(
            f"`{change.path}` looks like {_article(reason)} {reason}. Files like this usually "
            "contain credentials and should never be committed. Its contents were not analyzed "
            "or sent to any AI provider."
        ),
        file=change.path,
        line_start=1,
        line_end=1,
        evidence=[Evidence(source="sentinel:files", text=f"Path matches {reason} pattern")],
        suggested_fix=(
            "Remove the file from the repository (and its history), add it to .gitignore, "
            "and rotate any credentials it contained."
        ),
        source=FindingSource.STATIC_ANALYZER,
        origins=["sentinel:sensitive-file"],
        rule_id="sensitive-file",
        tags=["secret"],
    )


def _secret_finding(
    path: str, rule_id: str, title: str, confidence: float, line: int, masked: str
) -> Finding:
    return Finding(
        category=Category.SECURITY,
        severity=Severity.HIGH,
        confidence=confidence,
        title=title,
        explanation=(
            "A credential appears to be hard-coded in source. Anyone with read access to "
            "the repository (or its history) can use it. The value was redacted before "
            "any AI analysis."
        ),
        file=path,
        line_start=line,
        line_end=line,
        evidence=[
            Evidence(
                source="sentinel:secrets", text=f"Matched {rule_id}: {masked}", file=path, line=line
            )
        ],
        suggested_fix=(
            "Load the value from an environment variable or secret manager, remove it from "
            "the code and git history, and rotate the credential."
        ),
        source=FindingSource.STATIC_ANALYZER,
        origins=[f"sentinel:secrets/{rule_id}"],
        rule_id=f"secret/{rule_id}",
        tags=["secret"],
    )
