SAFE_ENV_TEMPLATES = (".env.example", ".env.sample", ".env.template", ".env.dist")

MAX_FILE_CHANGED_LINES = 4000
MINIFIED_AVG_LINE = 400


@dataclass
class FilterOutcome:
    changeset: ChangeSet
    findings: list[Finding] = field(default_factory=list)
    redactions: int = 0


def _matches_ignore(path: str, patterns: list[str]) -> bool:
    for raw in patterns:
        pat = raw.strip()
        if not pat or pat.startswith("#"):
            continue
        if pat.endswith("/"):
            if path.startswith(pat) or f"/{pat}" in f"/{path}":
                return True
            continue
        if fnmatch.fnmatch(path, pat) or fnmatch.fnmatch(posixpath.basename(path), pat):
            return True
        if fnmatch.fnmatch(path, f"*/{pat}"):
            return True
    return False


def sensitive_file_reason(path: str) -> tuple[Severity, str] | None:
    base = posixpath.basename(path).lower()
    if base in SAFE_ENV_TEMPLATES:
        return None
    for glob, severity, reason in SENSITIVE_FILES:
        if fnmatch.fnmatch(base, glob):
            return severity, reason
    return None


def _is_generated(change: FileChange) -> bool:
    low = change.path.lower()
    if any(low.startswith(d) or f"/{d}" in low for d in GENERATED_DIRS):
        return True
    if low.endswith(GENERATED_SUFFIXES):
        return True
    head = [ln.content for h in change.hunks[:1] for ln in h.lines[:5]]
    return any(marker in line for line in head for marker in GENERATED_MARKERS)


def _is_minified(change: FileChange) -> bool:
    if change.language not in (Language.JAVASCRIPT, Language.TYPESCRIPT) and not (
        change.path.endswith(".css")
    ):
        return False
    lines = [ln.content for h in change.hunks for ln in h.lines if ln.kind is LineKind.ADDED]
    if not lines:
        return False
    avg = sum(len(x) for x in lines) / len(lines)
    return avg > MINIFIED_AVG_LINE


def _skip_reason(change: FileChange, ignore: list[str]) -> str | None:
    base = posixpath.basename(change.path).lower()
    ext = posixpath.splitext(base)[1]
    if change.is_binary or ext in BINARY_EXTENSIONS:
        return "binary file"
    if base in LOCK_FILES:
        return "lock file"
    if _matches_ignore(change.path, ignore):
        return "ignored by .sentinel.yml"
    if _is_generated(change):
        return "generated file"
    if _is_minified(change):
        return "minified file"
    if change.additions + change.deletions > MAX_FILE_CHANGED_LINES:
        return f"too large ({change.additions + change.deletions} changed lines)"
    if any("\x00" in ln.content for h in change.hunks for ln in h.lines):
        return "binary content"
    return None


def filter_changeset(
    changeset: ChangeSet,
    *,
    ignore: list[str] | None = None,
    languages: list[Language] | None = None,
) -> FilterOutcome:
    ignore = ignore or []
    enabled = set(languages) if languages else None
    kept: list[FileChange] = []
    skipped: list[SkippedFile] = list(changeset.skipped)
    findings: list[Finding] = []
    redactions = 0

    for change in changeset.files:
        sensitive = sensitive_file_reason(change.path)
        if sensitive is not None:
            severity, reason = sensitive
            skipped.append(
                SkippedFile(
                    path=change.path, reason=f"sensitive file ({reason}) — never sent to AI"
                )
            )
            if change.change_type is not ChangeType.DELETED:
                findings.append(_sensitive_file_finding(change, severity, reason))
            continue

        skip = _skip_reason(change, ignore)
        if skip is not None:
            skipped.append(SkippedFile(path=change.path, reason=skip))
            continue

        # Secret scan + in-place redaction of every diff line (context lines included,
        # since the whole hunk is shown to the model).
        for hunk in change.hunks:
            for ln in hunk.lines:
                if ln.kind is LineKind.ADDED and ln.new_lineno is not None:
                    for m in scan_line(ln.content, ln.new_lineno):
                        findings.append(
                            _secret_finding(
                                change.path,
                                m.rule.id,
                                m.rule.title,
                                m.rule.confidence,
                                m.line,
                                m.masked,
                            )
                        )
                redacted, matches = redact_line(ln.content)
                if matches:
                    ln.content = redacted
                    redactions += len(matches)

        if enabled is not None and change.language not in enabled:
            skipped.append(
                SkippedFile(path=change.path, reason=f"language not enabled ({change.language})")
            )
            continue
        kept.append(change)

    filtered = changeset.model_copy(update={"files": kept, "skipped": skipped})
    return FilterOutcome(changeset=filtered, findings=findings, redactions=redactions)


def _sensitive_file_finding(change: FileChange, severity: Severity, reason: str) -> Finding:
    return Finding(
        category=Category.SECURITY,
        severity=severity,
        confidence=0.9,
        title=f"Sensitive file committed: {posixpath.basename(change.path)}",
        explanation=(
            f"`{change.path}` looks like a {reason}. Files like this usually contain "
            "credentials and should never be committed. Its contents were not analyzed "
            "or sent to any AI provider."
        ),
        file=change.path,
        line_start=1,
        line_end=1,
        evidence=[Evidence(source="sentinel:files", text=f"Path matches {reason} pattern")],
        suggested_fix=(
            "Remove the file from the repository (and its history), add it to .gitignore, "
            "and rotate any credentials it contained."
        ),
        source=FindingSource.STATIC_ANALYZER,
        origins=["sentinel:sensitive-file"],
        rule_id="sensitive-file",
        tags=["secret"],
    )


def _secret_finding(
    path: str, rule_id: str, title: str, confidence: float, line: int, masked: str
) -> Finding:
    return Finding(
        category=Category.SECURITY,
        severity=Severity.HIGH,
        confidence=confidence,
        title=title,
        explanation=(
            "A credential appears to be hard-coded in source. Anyone with read access to "
            "the repository (or its history) can use it. The value was redacted before "
            "any AI analysis."
        ),
        file=path,
        line_start=line,
        line_end=line,
        evidence=[
            Evidence(
                source="sentinel:secrets", text=f"Matched {rule_id}: {masked}", file=path, line=line
            )
        ],
        suggested_fix=(
            "Load the value from an environment variable or secret manager, remove it from "
            "the code and git history, and rotate the credential."
        ),
        source=FindingSource.STATIC_ANALYZER,
        origins=[f"sentinel:secrets/{rule_id}"],
        rule_id=f"secret/{rule_id}",
        tags=["secret"],
    )
