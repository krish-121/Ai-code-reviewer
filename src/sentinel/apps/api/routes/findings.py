"""Finding and fix routes: read a finding, change its status, generate and apply fixes.

A fix is generated by the worker (job kind ``fix``), not inside the request. Applying a
fix writes files, so it is only allowed for reviews of local repositories and goes through
``FixService.apply``, which refuses fixes whose target files changed since generation.
"""

# No `from __future__ import annotations`: FastAPI evaluates route signatures.

from typing import Any

from fastapi import APIRouter, HTTPException, Response

from sentinel.apps.api.dependencies import (
    MUTATING,
    ContextDep,
    SessionDep,
    UserDep,
    finding_or_404,
    fix_or_404,
)
from sentinel.apps.api.serializers import (
    UpdateFinding,
    event_json,
    finding_json,
    fix_json,
    is_local,
)
from sentinel.core.domain.errors import SentinelError
from sentinel.infrastructure.database.models import Finding as FindingRow
from sentinel.infrastructure.database.store import Store
from sentinel.infrastructure.queue import jobs

router = APIRouter(prefix="/api", tags=["findings"])

FIX_JOB = "fix"
REJECTED = "rejected"


@router.get("/findings/{finding_id}")
def get_finding(finding_id: str, session: SessionDep, user: UserDep) -> dict[str, Any]:
    """A finding with its history and every fix attempted for it."""
    store = Store(session)
    row = finding_or_404(store, user, finding_id)
    local = is_local(row.review)
    return {
        "finding": finding_json(row),
        "events": [event_json(e) for e in store.events(row.id)],
        "fixes": [fix_json(f, local) for f in store.fixes_for_finding(row.id)],
    }


@router.patch("/findings/{finding_id}", dependencies=MUTATING)
def update_finding(
    finding_id: str, body: UpdateFinding, session: SessionDep, user: UserDep
) -> dict[str, Any]:
    """Accept, dismiss or reopen a finding (recorded in its history)."""
    store = Store(session)
    row = finding_or_404(store, user, finding_id)
    store.set_status(row, body.status, user, body.note)
    return finding_json(row)


@router.post("/findings/{finding_id}/fix", status_code=202, dependencies=MUTATING)
def request_fix(finding_id: str, session: SessionDep, user: UserDep) -> dict[str, str]:
    """Queue fix generation for a finding and return the fix id."""
    store = Store(session)
    fix = store.create_fix(finding_or_404(store, user, finding_id))
    jobs.enqueue(session, FIX_JOB, {"fix_id": fix.id}, max_attempts=1)
    return {"id": fix.id}


@router.get("/fixes/{fix_id}")
def get_fix(fix_id: str, session: SessionDep, user: UserDep) -> dict[str, Any]:
    """One fix attempt (polled by the UI while the fix is being generated)."""
    fix = fix_or_404(Store(session), user, fix_id)
    finding = session.get_one(FindingRow, fix.finding_id)
    return fix_json(fix, is_local(finding.review))


@router.get("/fixes/{fix_id}/patch")
def get_patch(fix_id: str, session: SessionDep, user: UserDep) -> Response:
    """Download the fix as a unified-diff ``.patch`` file."""
    fix = fix_or_404(Store(session), user, fix_id)
    return Response(
        fix.patch or "",
        media_type="text/x-diff",
        headers={"Content-Disposition": f'attachment; filename="{fix.id}.patch"'},
    )


@router.post("/fixes/{fix_id}/apply", dependencies=MUTATING)
def apply_fix(
    fix_id: str, context: ContextDep, session: SessionDep, user: UserDep
) -> dict[str, Any]:
    """Write a validated fix into the local working tree."""
    fix_or_404(Store(session), user, fix_id)
    session.commit()  # the service opens its own transaction
    try:
        written = context.fixes.apply(fix_id)
    except SentinelError as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc
    return {"applied": written}


@router.post("/fixes/{fix_id}/reject", dependencies=MUTATING)
def reject_fix(fix_id: str, session: SessionDep, user: UserDep) -> dict[str, str]:
    """Mark a fix as rejected so it is no longer offered."""
    fix = fix_or_404(Store(session), user, fix_id)
    fix.status = REJECTED
    return {"status": fix.status}
